import assert from 'node:assert/strict';
import { verifyPinnedReorder } from './verify-pinned-reorder.mjs';
import { verifyThreadActions } from './verify-thread-actions.mjs';

export async function verifyRecentThreads({ page, application, threads, originalTitle, capture, directory }) {
  const sidebar = page.locator('.thread-list');
  const pinned = sidebar.getByRole('region', { name: '已置顶', exact: true });
  const recent = sidebar.getByRole('region', { name: '最近聊天', exact: true });
  const pinnedRows = threads.filter(thread => thread.pinned);
  const ordinary = threads.filter(thread => !thread.pinned && !thread.archived);
  const archived = threads.find(thread => thread.archived);
  const row = title => sidebar.getByRole('button', { name: title, exact: true });
  await pinned.getByRole('button', { name: pinnedRows[0].title, exact: true }).waitFor();
  assert.equal(await recent.getByRole('button', { name: pinnedRows[0].title, exact: true }).count(), 0);
  assert.equal(await row(archived.title).count(), 0, 'Archived chats stay out of both sidebar sections');
  assert.equal(await row(ordinary.at(-1).title).count(), 0, 'The oldest fixture starts beyond the first batch');
  assert.equal(await row(originalTitle).getAttribute('aria-current'), 'page', 'The current older chat remains visible outside the first batch');
  assert.equal(await recent.locator('.thread-row').count(), 11, 'Ten recent chats plus the current older chat are initially visible');
  const toggle = pinned.getByRole('button', { name: '已置顶', exact: true });
  const heading = await toggle.evaluate(element => { const style = getComputedStyle(element); return { fontSize: style.fontSize, lineHeight: style.lineHeight, weight: style.fontWeight, height: element.getBoundingClientRect().height }; });
  assert.deepEqual(heading, { fontSize: '14px', lineHeight: '21px', weight: '500', height: 30 });
  const content = pinned.locator('.thread-section-content');
  assert.equal(await content.evaluate(element => getComputedStyle(element).transitionDuration), '0.3s, 0.3s');
  assert.equal(await content.evaluate(element => getComputedStyle(element).transitionTimingFunction), 'cubic-bezier(0.19, 1, 0.22, 1), cubic-bezier(0.19, 1, 0.22, 1)');
  await content.evaluate(element => { window.nookSectionTransitions = []; element.addEventListener('transitionend', event => { if (event.target === element && window.nookSectionTransitions.length < 20) window.nookSectionTransitions.push(event.propertyName); }); });
  await toggle.focus(); await toggle.press('Enter');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await row(pinnedRows[0].title).count(), 0);
  assert.equal(await toggle.evaluate(element => document.activeElement === element), true);
  assert.equal(await content.evaluate(element => element.inert && element.getAttribute('aria-hidden') === 'true'), true);
  await page.waitForFunction(() => window.nookSectionTransitions.includes('grid-template-rows') && document.querySelector('.thread-section-content[data-collapsed="true"]').getBoundingClientRect().height === 0);
  await toggle.press('Space'); await row(pinnedRows[0].title).waitFor();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  try {
    assert.equal(await content.evaluate(element => getComputedStyle(element).transitionDuration), '0s');
    await toggle.press('Enter');
    await page.waitForFunction(() => document.querySelector('.thread-section-content[data-collapsed="true"]')?.getBoundingClientRect().height === 0);
    assert.equal(await content.locator('.thread-row').count(), 0);
    await toggle.press('Space'); await row(pinnedRows[0].title).waitFor();
  } finally { await page.emulateMedia({ reducedMotion: 'no-preference' }); }
  await toggle.press('Enter');
  await page.reload(); await page.getByLabel('消息', { exact: true }).waitFor();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false', 'Reload retains the pinned section preference');
  assert.equal(await recent.getByRole('button', { name: '最近聊天', exact: true }).getAttribute('aria-expanded'), 'true', 'The recent preference is independent');
  assert.equal(await row(pinnedRows[0].title).count(), 0);
  await toggle.focus(); await toggle.press('Space'); await row(pinnedRows[0].title).waitFor();
  await toggle.evaluate(element => { window.nookRapidToggleKeys = []; element.addEventListener('keydown', event => { if (['Enter', ' '].includes(event.key) && window.nookRapidToggleKeys.length < 2) window.nookRapidToggleKeys.push(performance.now()); }); });
  await toggle.press('Enter'); await toggle.press('Space');
  await page.waitForFunction(() => window.nookRapidToggleKeys.length === 2 && performance.now() - window.nookRapidToggleKeys[1] >= 350);
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
  assert.equal(await content.locator('.thread-row').count(), pinnedRows.length, 'A stale collapse timer cannot remove rows after rapid reopening');
  assert.ok(await page.evaluate(() => window.nookRapidToggleKeys[1] - window.nookRapidToggleKeys[0] < 300), 'The native keyboard reversal happened before the collapse deadline');
  const pinnedReorder = await verifyPinnedReorder({ page, application, pinnedRows, originalTitle, capture });
  const more = recent.getByRole('button', { name: '显示更多最近聊天', exact: true });
  for (let index = 10; index < ordinary.length; index += 10) {
    await more.focus(); await more.press('Enter'); await row(ordinary[index].title).waitFor();
    assert.equal(await row(ordinary[index].title).evaluate(element => document.activeElement === element), true, 'Expanding each batch focuses its first new row, including the final batch');
  }
  await row(ordinary.at(-1).title).waitFor();
  assert.equal(await row(originalTitle).getAttribute('aria-current'), 'page', 'Showing more never activates a chat');
  assert.equal(await page.getByLabel('消息', { exact: true }).inputValue(), 'CHAT_NAV_DRAFT_KEEP');
  await sidebar.evaluate(element => { element.scrollTop = 0; });
  await page.mouse.move(1, 1);
  await capture('110-sidebar-groups-light.png');
  const recentToggle = recent.getByRole('button', { name: '最近聊天', exact: true });
  await recentToggle.click(); assert.equal(await recentToggle.getAttribute('aria-expanded'), 'false');
  await page.getByLabel('消息', { exact: true }).fill('CHAT_NAV_DRAFT_TYPING');
  assert.equal(await recentToggle.getAttribute('aria-expanded'), 'false', 'Typing in the current chat is not a reveal request');
  await page.getByLabel('消息', { exact: true }).fill('CHAT_NAV_DRAFT_KEEP');
  await page.keyboard.press('Control+k');
  const palette = page.getByRole('dialog', { name: '搜索与命令', exact: true });
  await palette.getByRole('combobox').fill(originalTitle);
  await palette.getByRole('option', { name: originalTitle, exact: true }).click(); await palette.waitFor({ state: 'hidden' });
  await row(originalTitle).waitFor();
  assert.equal(await recentToggle.getAttribute('aria-expanded'), 'true', 'Explicitly selecting the already active chat reveals its collapsed section');
  assert.equal(await row(originalTitle).getAttribute('aria-current'), 'page');
  await recentToggle.click(); await page.keyboard.press('Control+k');
  await palette.getByRole('combobox').fill(ordinary.at(-1).title);
  const option = palette.getByRole('option', { name: ordinary.at(-1).title, exact: true });
  await option.click(); await palette.waitFor({ state: 'hidden' });
  await row(ordinary.at(-1).title).waitFor();
  assert.equal(await recentToggle.getAttribute('aria-expanded'), 'true', 'Selecting a chat through search reveals its collapsed section');
  assert.equal(await row(ordinary.at(-1).title).getAttribute('aria-current'), 'page');
  await page.getByRole('button', { name: '置顶聊天', exact: true }).click();
  await pinned.getByRole('button', { name: ordinary.at(-1).title, exact: true }).waitFor();
  assert.equal(await recent.getByRole('button', { name: ordinary.at(-1).title, exact: true }).count(), 0);
  await page.getByRole('button', { name: '取消置顶', exact: true }).click();
  await recent.getByRole('button', { name: ordinary.at(-1).title, exact: true }).waitFor();
  await row(originalTitle).click();
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="消息"]')?.value === 'CHAT_NAV_DRAFT_KEEP');
  const actions = await verifyThreadActions({ page, application, threads, originalTitle, capture, directory });
  return { fixtures: threads.length, pinnedReorder, actions, pinnedSections: true, keyboardCollapse: true, independentCollapseReload: true, collapseTransition: true, reducedMotion: true, rapidCollapseReversal: true, sameActiveSearchReveal: true, typingKeepsCollapsed: true, paginationFocus: true, currentChatBeyondFirstBatch: true, searchRevealsCollapsedSection: true, pinAndUnpin: true, originalDraftRetained: true };
}
